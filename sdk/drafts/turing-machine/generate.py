#!/usr/bin/env python3
"""Generate the MCF54455 module unit; the base owns the generator host."""
import importlib.util
from pathlib import Path
import subprocess
import sys
import tempfile
HERE = Path(__file__).resolve().parent
ROOT = next(p for p in HERE.parents if (p / 'sdk/runtime/loader/build.py').is_file())
spec = importlib.util.spec_from_file_location('turing_codegen', ROOT / 'sdk/runtime/m68k_codegen.py')
codegen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(codegen)
FLAGS = ['-mcpu=54455', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin',
         '-fno-common', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-fno-tree-loop-distribute-patterns',
         '-fno-auto-inc-dec', *codegen.FLAGS, '-I'+str(ROOT/'sdk/machines/octatrack/include')]
def generate():
    with tempfile.TemporaryDirectory() as folder:
        asm, obj = Path(folder) / 'turing.s', Path(folder) / 'turing.o'
        subprocess.run(['m68k-elf-gcc', *FLAGS, '-S', 'turing.c', '-o', str(asm)], cwd=HERE, check=True)
        subprocess.run(['m68k-elf-as', '-mcpu=54455', str(asm), '-o', str(obj)], check=True)
        codegen.check_mcf54455([obj])
        return '| Generated by generate.py; edit turing.c / hooks.s.\n' + asm.read_text() + '\n' + (HERE / 'hooks.s').read_text()
if __name__ == '__main__':
    source = generate()
    dest = HERE / 'turing.s'
    if '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit('turing.s is stale: run generate.py')
        print('turing.s matches MCF54455 source and passes the SDK codegen guard')
    else:
        dest.write_text(source)
