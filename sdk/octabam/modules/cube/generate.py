#!/usr/bin/env python3
"""CUBE's generated sources: cube_tables.inc (the control tables, from
cube_model.py, so the ColdFire's integer steps are the model's), cube.s
(cube.c compiled freestanding for the ColdFire, Analog BD's flags) and
cube_voice.asm (the DSP section the build places: the seam stub, then the
engine).

    python3 modules/cube/generate.py [--check]
"""
import pathlib
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cube_model as M  # noqa: E402

FLAGS = ['-mcpu=5407', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common', '-fno-jump-tables',
         '-fno-asynchronous-unwind-tables', '-fno-ident', '-fomit-frame-pointer', '-fno-zero-initialized-in-bss',
         '-Wall', '-Wextra', '-Werror']


def table(name, typ, values):
    rows = ",\n".join("    " + ", ".join(str(v) for v in values[i:i + 8]) for i in range(0, len(values), 8))
    return f"static const {typ} {name}[{len(values)}] = {{\n{rows}\n}};\n"


def tables():
    return ("/* Generated by generate.py from cube_model.py: do not edit. */\n"
            f"#define CUBE_MININC {M.MININC}u\n#define CUBE_MAXINC {M.MAXINC}u\n"
            + table("CUBE_CENT", "uint32_t", M.CENT) + table("CUBE_UNIC", "int32_t", M.UNIC)
            + table("CUBE_FMLIN", "uint32_t", M.FMLIN) + table("CUBE_MIXG", "uint32_t", M.MIXG))


def voice():
    return ("; Generated by generate.py from cube_seam.asm and cube_engine.asm: do not edit.\n"
            + (HERE / "cube_seam.asm").read_text() + "\n" + (HERE / "cube_engine.asm").read_text())


def main():
    check = "--check" in sys.argv
    for name, text in (("cube_tables.inc", tables()), ("cube_voice.asm", voice())):
        if check and (HERE / name).read_text() != text:
            raise SystemExit(f"stale: {name}")
        if not check:
            (HERE / name).write_text(text)
    with tempfile.TemporaryDirectory() as tmp:
        dest = pathlib.Path(tmp) / "cube.s"
        subprocess.run(["m68k-elf-gcc", *FLAGS, "-S", "cube.c", "-o", str(dest)], cwd=HERE, check=True)
        body = "| Generated by generate.py from cube.c.\n" + dest.read_text()
    if ".comm" in body or ".bss" in body:
        raise SystemExit("cube.c: a DRAM unit's .bss is never cleared; initialise every static")
    out = HERE / "cube.s"
    if check:
        if out.read_text() != body:
            raise SystemExit("stale: cube.s")
        print("cube: generated sources match")
    else:
        out.write_text(body)
        print("cube: cube_tables.inc, cube_voice.asm, cube.s generated")


if __name__ == "__main__":
    main()
